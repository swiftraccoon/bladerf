use std::collections::BTreeMap;
use std::fmt::Write;

use anyhow::{Context, Result, bail};
use serde_json::Value;
use url::Url;

use crate::catalog::{Catalog, array, field, text};

fn markdown(value: &str) -> String {
    let mut result = String::new();
    for character in value.chars() {
        match character {
            '&' => result.push_str("&amp;"),
            '<' => result.push_str("&lt;"),
            '>' => result.push_str("&gt;"),
            '\\' | '`' | '*' | '_' | '[' | ']' | '|' | '#' => {
                result.push('\\');
                result.push(character);
            }
            '\n' | '\r' => result.push(' '),
            other => result.push(other),
        }
    }
    result
}

fn integer(value: &Value) -> Result<String> {
    let raw = value
        .as_i64()
        .context("expected signed 64-bit integer")?
        .to_string();
    let (sign, digits) = raw
        .strip_prefix('-')
        .map_or(("", raw.as_str()), |digits| ("-", digits));
    let mut result = sign.to_owned();
    for (index, character) in digits.chars().enumerate() {
        if index != 0 && (digits.len() - index).is_multiple_of(3) {
            result.push(',');
        }
        result.push(character);
    }
    Ok(result)
}

fn claim_value(value: &Value) -> Result<String> {
    match text(value, "kind")? {
        "integer" => Ok(format!(
            "{} {}",
            integer(field(value, "value")?)?,
            markdown(text(value, "unit")?)
        )),
        "integer_range" => Ok(format!(
            "{} to {} {}",
            integer(field(value, "minimum")?)?,
            integer(field(value, "maximum")?)?,
            markdown(text(value, "unit")?)
        )),
        "text" => Ok(markdown(text(value, "value")?)),
        "boolean" => Ok(field(value, "value")?
            .as_bool()
            .context("expected boolean fact value")?
            .to_string()),
        other => bail!("unsupported fact value kind {other}"),
    }
}

fn strings(values: &[Value]) -> Result<String> {
    let values: Result<Vec<_>> = values
        .iter()
        .map(|v| {
            v.as_str()
                .map(markdown)
                .context("expected string list item")
        })
        .collect();
    let values = values?;
    Ok(if values.is_empty() {
        "not asserted".to_owned()
    } else {
        values.join(", ")
    })
}

fn evidence_url(source: &Value, locator: &Value) -> Result<Url> {
    let mut url = Url::parse(text(source, "url")?).context("parse validated evidence URL")?;
    if text(locator, "kind")? == "pdf_page" {
        let page = field(locator, "page")?
            .as_u64()
            .context("expected PDF page")?;
        url.set_fragment(Some(&format!("page={page}")));
    } else if let Some(fragment) = locator.get("fragment").and_then(Value::as_str) {
        url.set_fragment(Some(fragment));
    }
    Ok(url)
}

fn link(label: &str, url: &Url) -> String {
    let destination = url
        .as_str()
        .replace('&', "&amp;")
        .replace('(', "%28")
        .replace(')', "%29")
        .replace('<', "%3C")
        .replace('>', "%3E");
    format!("[{}](<{destination}>)", markdown(label))
}

pub(crate) fn handbook(catalog: &Catalog) -> Result<String> {
    let mut output = String::from(
        "<!-- Generated by bladerf-docs from the tracked catalog. Edit the catalog, then render. -->\n\n(fact-catalog)=\n# Source-qualified fact catalog\n\n",
    );
    output.push_str("These records support reference reading; they do not validate an equipment configuration or describe the state of a connected radio.\n\n");
    output.push_str("The {download}`canonical JSON <../knowledge/catalog.json>` and {download}`JSON Schema <../knowledge/catalog.schema.json>` are available for inspection and reuse. Numeric ranges retain their source scope and conditions. Empty scope lists mean **not asserted**, rather than all revisions or all software. Reviews here are source checks; their method is shown and does not imply independent human review or hardware measurements.\n\n");
    let sources: BTreeMap<_, _> = catalog
        .sources()?
        .iter()
        .map(|s| Ok((text(s, "id")?, s)))
        .collect::<Result<_>>()?;
    let claims: BTreeMap<_, _> = catalog
        .claims()?
        .iter()
        .map(|c| Ok((text(c, "id")?, c)))
        .collect::<Result<_>>()?;
    for (id, claim) in claims {
        writeln!(
            output,
            "(fact-{id})=\n## {}\n",
            markdown(text(claim, "title")?)
        )?;
        writeln!(output, "{}\n", markdown(text(claim, "statement")?))?;
        writeln!(
            output,
            "**Value:** {}. **Evidence kind:** `{}`.\n",
            claim_value(field(claim, "value")?)?,
            text(claim, "evidence_kind")?
        )?;
        let scope = field(claim, "scope")?;
        let software = field(scope, "software")?
            .as_object()
            .context("expected software scope object")?;
        let software: Result<Vec<_>> = software
            .iter()
            .map(|(name, version)| {
                Ok(format!(
                    "{} {}",
                    markdown(name),
                    markdown(
                        version
                            .as_str()
                            .context("expected software version string")?
                    )
                ))
            })
            .collect();
        let software = software?;
        writeln!(
            output,
            "**Scope:** {}; FPGA {}; PCB {}; software {}; mode {}.\n",
            markdown(text(scope, "board_family")?),
            strings(array(scope, "fpga_variants")?)?,
            strings(array(scope, "pcb_revisions")?)?,
            if software.is_empty() {
                "not asserted".to_owned()
            } else {
                software.join(", ")
            },
            markdown(text(scope, "mode")?)
        )?;
        output.push_str("**Conditions:**\n\n");
        for condition in array(claim, "conditions")? {
            writeln!(
                output,
                "- {}",
                markdown(condition.as_str().context("expected condition string")?)
            )?;
        }
        if let Some(derivation) = claim.get("derivation").and_then(Value::as_str) {
            writeln!(output, "\n**Derivation:** {}", markdown(derivation))?;
        }
        output.push_str("\n**Evidence:**\n\n");
        for evidence in array(claim, "evidence")? {
            let source = sources
                .get(text(evidence, "source_id")?)
                .context("validated source no longer present")?;
            let locator = field(evidence, "locator")?;
            let location = match text(locator, "kind")? {
                "pdf_page" => format!(
                    "physical PDF page {}, printed label {}",
                    field(locator, "page")?,
                    markdown(text(locator, "printed_label")?)
                ),
                "symbol" => format!("symbol {}", markdown(text(locator, "symbol")?)),
                "section" => format!("section {}", markdown(text(locator, "section")?)),
                other => bail!("unsupported locator {other}"),
            };
            writeln!(
                output,
                "- {} — {}, {}.",
                link(text(source, "title")?, &evidence_url(source, locator)?),
                markdown(text(source, "revision")?),
                location
            )?;
        }
        let review = field(claim, "review")?;
        writeln!(
            output,
            "\n**Review:** `{}`; method `{}`. Record `{id}`.\n",
            text(review, "status")?,
            text(review, "method")?
        )?;
    }
    output.push_str("## Source identities\n\nThe hashes identify the bytes inspected. A matching URL alone does not identify the same document revision. Pinned source-code URLs identify a Git commit; web-page hashes identify the retrieved snapshot.\n\n");
    for (id, source) in &sources {
        writeln!(
            output,
            "### {}\n\n- Source ID: `{id}`\n- Publisher: {}\n- Revision: {}\n- {}\n- SHA256: `{}`\n",
            markdown(text(source, "title")?),
            markdown(text(source, "publisher")?),
            markdown(text(source, "revision")?),
            link("Original source", &Url::parse(text(source, "url")?)?),
            text(source, "sha256")?
        )?;
    }
    output.push_str("## Issues and coverage gaps\n\nThese records retain source disagreements and unresolved coverage. They are not automatically resolved by schema validation.\n\n");
    let issues: BTreeMap<_, _> = catalog
        .issues()?
        .iter()
        .map(|i| Ok((text(i, "id")?, i)))
        .collect::<Result<_>>()?;
    if issues.is_empty() {
        output.push_str("No issues recorded in this catalog snapshot. This does not establish complete coverage.\n");
    }
    for (id, issue) in issues {
        writeln!(
            output,
            "### {}\n\n{}\n\nStatus `{}`; kind `{}`; issue `{id}`.\n",
            markdown(text(issue, "title")?),
            markdown(text(issue, "summary")?),
            text(issue, "status")?,
            text(issue, "kind")?
        )?;
        if let Some(decision) = issue.get("decision").and_then(Value::as_str) {
            writeln!(
                output,
                "**Current interpretation:** {}\n",
                markdown(decision)
            )?;
        }
        let claim_ids = array(issue, "claim_ids")?;
        if !claim_ids.is_empty() {
            let links: Result<Vec<_>> = claim_ids
                .iter()
                .map(|id| {
                    let id = id.as_str().context("expected claim reference")?;
                    Ok(format!("{{ref}}`fact-{id}`"))
                })
                .collect();
            writeln!(output, "Related claims: {}.\n", links?.join(", "))?;
        }
        let source_ids = array(issue, "source_ids")?;
        for id in source_ids {
            let source = sources
                .get(id.as_str().context("expected source reference")?)
                .context("validated issue source missing")?;
            writeln!(
                output,
                "- {}",
                link(text(source, "title")?, &Url::parse(text(source, "url")?)?)
            )?;
        }
        output.push('\n');
    }
    output.truncate(output.trim_end_matches('\n').len());
    output.push('\n');
    Ok(output)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn renders_signed_extremes_and_escapes_document_text() {
        assert_eq!(
            integer(&Value::from(i64::MIN)).unwrap(),
            "-9,223,372,036,854,775,808"
        );
        assert_eq!(
            markdown("[link](x) <script>\nnext"),
            "\\[link\\](x) &lt;script&gt; next"
        );
        assert_eq!(
            markdown("x` <img src=\"https://invalid.test/a\">"),
            "x\\` &lt;img src=\"https://invalid.test/a\"&gt;"
        );
    }

    #[test]
    fn preserves_url_delimiters_and_literal_entity_sequences() {
        let url = Url::parse("https://example.org/a)b?q=1&copy;x=2").unwrap();
        assert_eq!(
            link("[source]", &url),
            "[\\[source\\]](<https://example.org/a%29b?q=1&amp;copy;x=2>)"
        );
    }
}
